CREATE TABLE IF NOT EXISTS mesas (
    id             SERIAL      PRIMARY KEY,
    nombre         TEXT        NOT NULL,
    sistema        TEXT        NOT NULL,
    descripcion    TEXT,
    tono           TEXT,
    horario        TEXT,
    estado         TEXT        NOT NULL DEFAULT 'abierta'
                               CHECK (estado IN ('abierta', 'cerrada')),
    nivel_inicial  INTEGER,
    jugadores_max  INTEGER,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_mesas_estado ON mesas (estado);

CREATE TABLE IF NOT EXISTS usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  TEXT    NOT NULL,
    rol            VARCHAR(16) NOT NULL DEFAULT 'usuario'
                   CHECK (rol IN ('usuario', 'gm', 'admin')),
    nombre         VARCHAR(120) NOT NULL,
    fecha_creacion TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS matchmaking (
    id                SERIAL      PRIMARY KEY,
    mesa_id           INTEGER     NOT NULL REFERENCES mesas (id) ON DELETE CASCADE,
    estado            TEXT        NOT NULL DEFAULT 'llamada_abierta'
                                  CHECK (estado IN ('llamada_abierta', 'cerrada', 'completa')),
    llamada_abierta_at TIMESTAMPTZ,
    fecha_creacion    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_matchmaking_mesa ON matchmaking (mesa_id);

-- B06: conteo de ocupación y registro de solicitudes (carrera por la última vacante).
ALTER TABLE mesas ADD COLUMN IF NOT EXISTS jugadores_actuales INT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS solicitudes_uniones (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mesa_id    INTEGER     NOT NULL REFERENCES mesas (id) ON DELETE CASCADE,
    usuario_id BIGINT      NOT NULL,
    estado     TEXT        NOT NULL DEFAULT 'pendiente'
                           CHECK (estado IN ('pendiente', 'aceptada', 'rechazada')),
    idem_key   VARCHAR(64),
    fecha      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_solicitudes_mesa_usuario ON solicitudes_uniones (mesa_id, usuario_id);

-- B07: sesiones y asistencias para el QR de asistencia (single-use, AE2 9).
CREATE TABLE IF NOT EXISTS sesiones (
    id         SERIAL      PRIMARY KEY,
    mesa_id    INTEGER     NOT NULL REFERENCES mesas (id) ON DELETE CASCADE,
    fecha      TIMESTAMPTZ NOT NULL DEFAULT now(),
    estado     TEXT        NOT NULL DEFAULT 'abierta'
                           CHECK (estado IN ('abierta', 'cerrada'))
);

CREATE TABLE IF NOT EXISTS asistencias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id  INTEGER     NOT NULL REFERENCES sesiones (id) ON DELETE CASCADE,
    usuario_id BIGINT      NOT NULL,
    fecha      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_asistencia_sesion_usuario UNIQUE (sesion_id, usuario_id)
);

CREATE INDEX IF NOT EXISTS idx_sesiones_mesa ON sesiones (mesa_id);

-- Cierre AE2: confirmación explícita del GM (B07/proveedor-email)
-- Confirmar la sesión dispara el evento sesion.confirmada y notif-api notifica
-- por SSE y emails a los miembros de la mesa. La columna es nullable porque
-- las sesiones históricas no la registraban, y confirmar es idempotente
-- (reconfirmar no vuelve a publicar el evento)
ALTER TABLE sesiones ADD COLUMN IF NOT EXISTS confirmada_at TIMESTAMPTZ;

-- F2: membresía por mesa (principio 2.1: roles contextuales, no de cuenta).
CREATE TABLE IF NOT EXISTS miembros_mesa (
    mesa_id    INTEGER NOT NULL REFERENCES mesas (id)    ON DELETE CASCADE,
    usuario_id BIGINT  NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    rol        TEXT    NOT NULL DEFAULT 'jugador' CHECK (rol IN ('master', 'jugador')),
    fecha      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (mesa_id, usuario_id)
);

CREATE INDEX IF NOT EXISTS idx_miembros_usuario ON miembros_mesa (usuario_id);

-- Backfill idempotente: cada mesa define su master y los aceptados entran como jugadores.
INSERT INTO miembros_mesa (mesa_id, usuario_id, rol)
  SELECT id, gm_id, 'master' FROM mesas WHERE gm_id IS NOT NULL
  ON CONFLICT (mesa_id, usuario_id) DO NOTHING;

INSERT INTO miembros_mesa (mesa_id, usuario_id, rol)
  SELECT s.mesa_id, s.usuario_id, 'jugador'
  FROM solicitudes_uniones s WHERE s.estado = 'aceptada'
  ON CONFLICT (mesa_id, usuario_id) DO NOTHING;

